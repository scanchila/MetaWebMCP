export function generateProjectZip(input) {
  const project = generateProjectFiles(input);
  const root = `${project.projectName}/`;
  const files = Object.fromEntries(Object.entries(project.files).map(([name, content]) => [`${root}${name}`, content]));
  return {
    projectName: project.projectName,
    fileName: `${project.projectName}.zip`,
    buffer: createZip(files),
    fileCount: Object.keys(files).length,
  };
}
