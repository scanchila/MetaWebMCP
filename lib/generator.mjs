function installGeneratedModule(html) {
  const moduleTag = '<script type="module" src="./src/webmcp.generated.js"></script>';
  if (/<\/body\s*>/i.test(html)) return html.replace(/<\/body\s*>/i, `  ${moduleTag}\n</body>`);
  return `${html}\n${moduleTag}\n`;
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
}

